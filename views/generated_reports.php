            <i class="fas fa-file-export mr-1"></i> Log New Report File
          </button>
        </div>
      </div>
    </div>
  </div>

  <!-- Main content -->
  <div class="content">
    <div class="container-fluid">

      <?php if (!empty($toast_message)): ?>
        <div class="alert alert-<?= $toast_type === 'Success' ? 'success' : 'danger' ?> alert-dismissible fade show" role="alert">
          <?= htmlspecialchars($toast_message) ?>
          <button type="button" class="close" data-dismiss="alert" aria-label="Close">
            <span aria-hidden="true">&times;</span>
          </button>
        </div>
      <?php endif; ?>

      <div class="row">
        <div class="col-lg-12">
          <div class="card card-navy card-outline">
            <div class="card-header">
              <h3 class="card-title"><i class="fas fa-folder-open mr-1"></i> Exported System Reports</h3>
            </div>
            <div class="card-body">
              <table id="example1" class="table table-bordered table-striped">
                <thead>
                  <tr>
                    <th>#</th>
                    <th>Report Type</th>
                    <th>Generated By</th>
                    <th>File Path</th>
                    <th>Generated At</th>
                    <th>Actions</th>
                  </tr>
                </thead>
                <tbody>
                  <?php foreach ($reports as $index => $rp): ?>
                    <tr>
                      <td><?= $index + 1 ?></td>
                      <td><strong><?= htmlspecialchars($rp['report_type']) ?></strong></td>
                      <td>
                        <?= htmlspecialchars($rp['generated_by_name']) ?>
                        <span class="badge badge-info ml-1"><?= ucfirst(htmlspecialchars($rp['role_name'] ?? 'User')) ?></span>
                      </td>
                      <td><code><?= htmlspecialchars($rp['file_path']) ?></code></td>
                      <td><?= date('M d, Y h:i A', strtotime($rp['generated_at'])) ?></td>
                      <td>
                        <!-- Download / View File Link -->
                        <a href="<?= htmlspecialchars($rp['file_path']) ?>" target="_blank" class="btn btn-info btn-sm" title="Download / Open File">
                          <i class="fas fa-download"></i>
                        </a>

                        <!-- Delete Form -->
                        <form action="" method="POST" class="d-inline" onsubmit="return confirm('Are you sure you want to delete this report file record?');">
                          <input type="hidden" name="action" value="delete">
                          <input type="hidden" name="report_file_id" value="<?= $rp['report_file_id'] ?>">
                          <button type="submit" class="btn btn-danger btn-sm" title="Delete Record">
                            <i class="fas fa-trash"></i>
                          </button>
                        </form>
                      </td>
                    </tr>
                  <?php endforeach; ?>
                </tbody>
              </table>
            </div>
          </div>
        </div>
      </div>
    </div>
  </div>
