<?php
if (!isset($_SESSION['user_id'])) {
  header("Location: dashboard.php?page=forbidden");
  exit;
}

$toast_message = '';
$toast_type = '';
$current_user_id = $_SESSION['user_id'];

// Handle Actions (Add / Delete Generated Report Log)
if ($_SERVER["REQUEST_METHOD"] === "POST" && isset($_POST['action'])) {
  if ($_POST['action'] === 'add') {
    $report_type = trim($_POST['report_type']);
    $file_path   = trim($_POST['file_path']);

    if (!empty($report_type) && !empty($file_path)) {
      try {
        $stmt = $pdo->prepare("INSERT INTO generated_reports (generated_by, report_type, file_path, generated_at) VALUES (?, ?, ?, NOW())");
        $stmt->execute([$current_user_id, $report_type, $file_path]);

        $toast_message = "Generated report record created successfully!";
        $toast_type = "Success";
      } catch (PDOException $e) {
        $toast_message = "Error recording report: " . $e->getMessage();
        $toast_type = "Error";
      }
    } else {
      $toast_message = "Please fill in all required fields.";
      $toast_type = "Error";
    }
  } elseif ($_POST['action'] === 'delete') {
    $report_file_id = intval($_POST['report_file_id']);

    try {
      // Fetch file path first if you wish to unlink physical files
      $fetch_stmt = $pdo->prepare("SELECT file_path FROM generated_reports WHERE report_file_id = ?");
      $fetch_stmt->execute([$report_file_id]);
      $report = $fetch_stmt->fetch(PDO::FETCH_ASSOC);

      if ($report && file_exists($report['file_path'])) {
        @unlink($report['file_path']);
      }

      $stmt = $pdo->prepare("DELETE FROM generated_reports WHERE report_file_id = ?");
      $stmt->execute([$report_file_id]);
      
      $toast_message = "Report record deleted successfully!";
      $toast_type = "Success";
    } catch (PDOException $e) {
      $toast_message = "Error deleting report: " . $e->getMessage();
      $toast_type = "Error";
    }
  }
}

// Fetch generated reports with details of the user who generated them
try {
  $stmt = $pdo->query("
    SELECT 
      gr.report_file_id,
      gr.report_type,
      gr.file_path,
      gr.generated_at,
      CONCAT(u.First_name, ' ', u.Last_name) AS generated_by_name,
      r.role_name
    FROM generated_reports gr
    INNER JOIN users u ON gr.generated_by = u.user_id
    LEFT JOIN roles r ON u.role_id = r.role_id
    ORDER BY gr.generated_at DESC
  ");
  $reports = $stmt->fetchAll(PDO::FETCH_ASSOC);
} catch (PDOException $e) {
  die("Database Error: " . $e->getMessage());
}
?>

